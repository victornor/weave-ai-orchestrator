import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import type { ProjectConfig } from '@openconductor/shared';
import { projectKeyFromUrl } from '../util/git.js';

function tomlString(s: string): string { return JSON.stringify(s); }

/**
 * Generate the per-workspace worktrunk user config (docs/research/worktrunk.md).
 * Every `wt` invocation passes `--config <this file>`, so the human's own worktrunk config is never read or written.
 */
export function renderWtConfig(projects: Array<Pick<ProjectConfig, 'url' | 'defaultBranch' | 'setupCommand'>>): string {
  const lines: string[] = [
    '# Generated by OpenConductor. Do not edit; regenerated whenever projects change.',
    '',
    '[list]',
    'json-schema = 2',
    '',
  ];
  const seen = new Set<string>();
  for (const p of projects) {
    const key = projectKeyFromUrl(p.url);
    if (seen.has(key)) continue;
    seen.add(key);
    const base = p.defaultBranch || 'main';
    const q = `projects.${tomlString(key)}`;
    lines.push(`[${q}]`, '');
    lines.push(`[[${q}.pre-start]]`);
    lines.push(`warm = ${tomlString(`wt step copy-ignored --from ${base} --to '{{ branch }}'`)}`, '');
    if (p.setupCommand && p.setupCommand.trim()) {
      lines.push(`[[${q}.pre-start]]`);
      lines.push(`setup = ${tomlString(p.setupCommand.trim())}`, '');
    }
  }
  return lines.join('\n');
}

export function writeWtConfig(path: string, projects: Array<Pick<ProjectConfig, 'url' | 'defaultBranch' | 'setupCommand'>>): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, renderWtConfig(projects), 'utf8');
}
